  // ===========================================================================
  const TALKS = {};
  const heard = () => (store.get('snappy.term.talks') || '').split(',').filter((id) => TALKS[id]);
  const hear = (id) => store.set('snappy.term.talks', [...heard().filter((x) => x !== id), id].join(','));
  function topic(id, words, beats) {
    TALKS[id] = beats;
    chat(words, () => { hear(id); return beats; });
  }
  function nextTalk() {
    const ids = Object.keys(TALKS), done = heard();
    let left = ids.filter((id) => !done.includes(id));
    // heard them all: start over, just not with the last one
    if (!left.length) { store.set('snappy.term.talks', ''); left = ids.filter((id) => id !== done[done.length - 1]); }
    const id = left[Math.floor(Math.random() * left.length)];
    hear(id);
    return TALKS[id];
  }
